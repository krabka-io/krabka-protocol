//! Emit a Rust source file that provides:
//!   - `CASES: &[Case]` — a static table of `(message, api_key, version, kind)` cases
//!   - `default_json_for(name)` — JSON the oracle should accept for default fixture
//!   - `encode_default(name, version)` — Rust-encoded bytes from `Default::default()`
//!   - `TAGGED_CASES`, `encode_tagged_fixture(name, version)` and
//!     `tagged_fixture_json_for(name, version)` — the same sweep over every
//!     message that has a tagged field, with each tagged field set
//!
//! `crates/protocol/tests/differential_all.rs` consumes the file with
//! `include!`.
//!
//! This module emits with `proc_macro2` and `quote!` instead of `writeln!`.
//! See `emit::api_key_enum_quote` for the overall pattern.

use proc_macro2::{Literal, TokenStream};
use quote::{format_ident, quote};

use crate::{
    emit::{EmitError, common::validate, tagged_fixture},
    ir::{MessageSpec, MessageType},
    name_conv,
};

/// Maximum version this emitter ever iterates to. Schemas with open-ended
/// `validVersions`, such as `0+`, would produce `i16::MAX` iterations, which is
/// wrong. In practice all active Kafka 4.2 schemas have bounded ranges, but
/// this cap is a defence against enormous output.
const MAX_VERSION_CAP: i16 = 127;

/// # Errors
/// Returns an error when the generated table is not valid Rust, which is an
/// emitter bug.
pub fn emit(specs: &[MessageSpec], schemas_version: &str) -> Result<String, EmitError> {
    let banner = format!(
        "// AUTO-GENERATED by krabka-protocol-codegen against {schemas_version}. Do not edit.\n\n"
    );

    let tokens = build_body(specs);

    // Validate at generation time; rustfmt (applied by the caller) does the
    // actual formatting. See `crate::fmt`.
    validate::<syn::File>(&tokens, "differential table")?;

    Ok(format!("{banner}{tokens}"))
}

fn build_body(specs: &[MessageSpec]) -> TokenStream {
    let mut ts = TokenStream::new();
    ts.extend(build_preamble());
    ts.extend(build_cases_table(specs));
    ts.extend(build_encode_default(specs));
    ts.extend(build_default_json_for(specs));
    ts.extend(build_tagged_fixture(specs));
    ts.extend(build_roundtrip(specs));
    ts.extend(build_header_versions(specs));
    ts.extend(build_strip_frame_header());
    ts
}

fn build_preamble() -> TokenStream {
    quote! {
        use std::{error::Error, fmt};

        use bytes::BytesMut;
        use krabka_protocol::{Encode, ProtocolError};

        #[derive(Debug, Clone, Copy)]
        pub struct Case {
            pub name: &'static str,
            pub api_key: i16,
            pub version: i16,
            pub kind: Kind,
        }

        #[derive(Debug, Clone, Copy)]
        pub enum Kind { Request, Response, RequestHeader, ResponseHeader }

        #[doc = " The owned and the borrowed encoding of one message."]
        pub type EncodedPair = (Vec<u8>, Vec<u8>);

        #[doc = " Why a table lookup, encode or round trip failed."]
        #[derive(Debug)]
        pub enum TableError {
            #[doc = " `name` identifies no message the table covers."]
            UnknownMessage(String),
            #[doc = " The codec rejected the message."]
            Protocol(ProtocolError),
            #[doc = " A decode left bytes behind."]
            TrailingBytes { name: String, remaining: usize },
        }

        impl fmt::Display for TableError {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                match self {
                    Self::UnknownMessage(name) => write!(f, "unknown message {name}"),
                    Self::Protocol(e) => write!(f, "{e}"),
                    Self::TrailingBytes { name, remaining } => {
                        write!(f, "{name}: {remaining} bytes left after decode")
                    }
                }
            }
        }

        impl Error for TableError {
            fn source(&self) -> Option<&(dyn Error + 'static)> {
                match self {
                    Self::Protocol(e) => Some(e),
                    Self::UnknownMessage(_) | Self::TrailingBytes { .. } => None,
                }
            }
        }

        impl From<ProtocolError> for TableError {
            fn from(e: ProtocolError) -> Self {
                Self::Protocol(e)
            }
        }

        fn encode_with<T: Encode>(message: &T, version: i16) -> Result<Vec<u8>, TableError> {
            let mut buf = BytesMut::new();
            message.encode(&mut buf, version)?;
            Ok(buf.to_vec())
        }

        #[doc = " Fails when a decode of `name` left bytes in `rest`."]
        fn expect_consumed(name: &str, rest: &[u8]) -> Result<(), TableError> {
            if rest.is_empty() {
                Ok(())
            } else {
                Err(TableError::TrailingBytes { name: name.to_owned(), remaining: rest.len() })
            }
        }
    }
}

fn build_cases_table(specs: &[MessageSpec]) -> TokenStream {
    let rows: Vec<TokenStream> = specs
        .iter()
        .flat_map(|s| {
            if s.valid_versions.is_empty() || s.internal {
                return Vec::new();
            }
            let kind_tokens: TokenStream = match s.message_type {
                MessageType::Request => quote!(Kind::Request),
                MessageType::Response => quote!(Kind::Response),
                MessageType::Header => match s.name.as_str() {
                    "RequestHeader" => quote!(Kind::RequestHeader),
                    "ResponseHeader" => quote!(Kind::ResponseHeader),
                    _ => return Vec::new(), // Unknown header type — skip
                },
                MessageType::Data => return Vec::new(),
            };
            let api_key = Literal::i16_unsuffixed(s.api_key.unwrap_or(0));
            let name_lit = Literal::string(&s.name);
            let max_v = s.valid_versions.max.min(MAX_VERSION_CAP);
            (s.valid_versions.min..=max_v)
                .map(|v| {
                    let v_lit = Literal::i16_unsuffixed(v);
                    let kind = kind_tokens.clone();
                    quote! {
                        Case { name: #name_lit, api_key: #api_key, version: #v_lit, kind: #kind },
                    }
                })
                .collect()
        })
        .collect();

    quote! {
        pub const CASES: &[Case] = &[
            #(#rows)*
        ];
    }
}

/// The schemas whose owned and borrowed codecs the table dispatches to.
fn table_specs(specs: &[MessageSpec]) -> impl Iterator<Item = &MessageSpec> {
    specs.iter().filter(|s| {
        !s.valid_versions.is_empty()
            && !s.internal
            && matches!(
                s.message_type,
                MessageType::Request | MessageType::Response | MessageType::Header
            )
    })
}

/// Chunk `arms` into private helpers named `<prefix>_<n>`, each a `match` on
/// `name` that returns `Ok(None)` for a name outside its chunk, plus the
/// public `dispatcher` that tries each helper and fails with
/// `TableError::UnknownMessage`.
///
/// `params` and `args` are the helpers' extra parameters and arguments after
/// `name`, and `ty` is the value one arm produces.
fn dispatch(
    arms: &[TokenStream],
    chunk: usize,
    prefix: &str,
    signature: (&TokenStream, &TokenStream, &TokenStream),
    public: &TokenStream,
) -> TokenStream {
    let (params, args, ty) = signature;
    let helpers: Vec<_> = arms
        .chunks(chunk)
        .enumerate()
        .map(|(index, chunk)| {
            let helper = format_ident!("{prefix}_{index}");
            quote! {
                fn #helper(name: &str, #params) -> Result<Option<#ty>, TableError> {
                    Ok(Some(match name {
                        #(#chunk)*
                        _ => return Ok(None),
                    }))
                }
            }
        })
        .collect();
    let tries = (0..helpers.len()).map(|index| {
        let helper = format_ident!("{prefix}_{index}");
        quote! {
            if let Some(value) = #helper(name, #args)? {
                return Ok(value);
            }
        }
    });
    quote! {
        #(#helpers)*
        #public {
            #(#tries)*
            Err(TableError::UnknownMessage(name.to_owned()))
        }
    }
}

fn build_encode_default(specs: &[MessageSpec]) -> TokenStream {
    let arms: Vec<TokenStream> = table_specs(specs)
        .map(|s| {
            let snake_ident = format_ident!("{}", name_conv::module_name(&s.name));
            let type_ident = format_ident!("{}", name_conv::type_name(&s.name));
            let name_lit = Literal::string(&s.name);
            quote! {
                #name_lit => encode_with(
                    &krabka_protocol::owned::#snake_ident::#type_ident::default(),
                    version,
                )?,
            }
        })
        .collect();
    dispatch(
        &arms,
        8,
        "encode_default",
        (&quote!(version: i16), &quote!(version), &quote!(Vec<u8>)),
        &quote! {
            #[doc = " The default value of message `name`, encoded at `version`."]
            #[doc = ""]
            #[doc = " # Errors"]
            #[doc = ""]
            #[doc = " Fails when `name` is unknown or the encode fails."]
            pub fn encode_default(name: &str, version: i16) -> Result<Vec<u8>, TableError>
        },
    )
}

fn build_default_json_for(specs: &[MessageSpec]) -> TokenStream {
    let arms: Vec<TokenStream> = table_specs(specs)
        .map(|s| {
            let snake_ident = format_ident!("{}", name_conv::module_name(&s.name));
            let name_lit = Literal::string(&s.name);
            quote! {
                #name_lit => krabka_protocol::owned::#snake_ident::default_json(version),
            }
        })
        .collect();
    dispatch(
        &arms,
        60,
        "default_json_for",
        (
            &quote!(version: i16),
            &quote!(version),
            &quote!(::serde_json::Value),
        ),
        &quote! {
            #[doc = " The JSON the oracle reads as the default value of message `name`."]
            #[doc = ""]
            #[doc = " # Errors"]
            #[doc = ""]
            #[doc = " Fails when `name` is unknown."]
            pub fn default_json_for(name: &str, version: i16) -> Result<::serde_json::Value, TableError>
        },
    )
}

/// The tagged-field sweep. It covers requests, responses and data records,
/// because the metadata records carry tagged fields too.
fn build_tagged_fixture(specs: &[MessageSpec]) -> TokenStream {
    let tagged: Vec<&MessageSpec> = specs
        .iter()
        .filter(|s| {
            !s.valid_versions.is_empty() && !s.internal && tagged_fixture::has_tagged_field(s)
        })
        .collect();

    let rows = tagged.iter().flat_map(|s| {
        let name_lit = Literal::string(&s.name);
        let max_v = s.valid_versions.max.min(MAX_VERSION_CAP);
        (s.valid_versions.min..=max_v).map(move |v| {
            let v_lit = Literal::i16_unsuffixed(v);
            quote! { TaggedCase { name: #name_lit, version: #v_lit }, }
        })
    });

    let encode_arms: Vec<TokenStream> = tagged
        .iter()
        .map(|s| {
            let snake_ident = format_ident!("{}", name_conv::module_name(&s.name));
            let type_ident = format_ident!("{}", name_conv::type_name(&s.name));
            let name_lit = Literal::string(&s.name);
            quote! {
                #name_lit => {
                    let owned = krabka_protocol::owned::#snake_ident::tagged_fixture();
                    let max = krabka_protocol::owned::#snake_ident::MAX_VERSION;
                    let full = encode_with(&owned, max)?;
                    let mut cur = full.as_slice();
                    let borrowed =
                        <krabka_protocol::borrowed::#snake_ident::#type_ident as krabka_protocol::DecodeBorrow>::decode_borrow(&mut cur, max)?;
                    expect_consumed(name, cur)?;
                    (encode_with(&owned, version)?, encode_with(&borrowed, version)?)
                }
            }
        })
        .collect();
    let encode = dispatch(
        &encode_arms,
        6,
        "encode_tagged_fixture",
        (
            &quote!(version: i16),
            &quote!(version),
            &quote!(EncodedPair),
        ),
        &quote! {
            #[doc = " The owned `tagged_fixture()` encoded at `version`, and the borrowed flavor of"]
            #[doc = " the same message encoded at `version`."]
            #[doc = ""]
            #[doc = " The borrowed message is decoded from the owned bytes at the highest version,"]
            #[doc = " where every tag is in range."]
            #[doc = ""]
            #[doc = " # Errors"]
            #[doc = ""]
            #[doc = " Fails when `name` has no tagged field, or an encode or decode fails."]
            pub fn encode_tagged_fixture(name: &str, version: i16) -> Result<EncodedPair, TableError>
        },
    );

    let json_arms = tagged.iter().map(|s| {
        let snake_ident = format_ident!("{}", name_conv::module_name(&s.name));
        let name_lit = Literal::string(&s.name);
        quote! {
            #name_lit => Ok(krabka_protocol::owned::#snake_ident::tagged_fixture_json(version)),
        }
    });

    quote! {
        #[derive(Debug, Clone, Copy)]
        pub struct TaggedCase {
            pub name: &'static str,
            pub version: i16,
        }

        pub const TAGGED_CASES: &[TaggedCase] = &[
            #(#rows)*
        ];

        #encode

        #[doc = " The JSON form of the tagged fixture of message `name` at `version`."]
        #[doc = ""]
        #[doc = " # Errors"]
        #[doc = ""]
        #[doc = " Fails when `name` has no tagged field."]
        pub fn tagged_fixture_json_for(name: &str, version: i16) -> Result<::serde_json::Value, TableError> {
            match name {
                #(#json_arms)*
                _ => Err(TableError::UnknownMessage(name.to_owned())),
            }
        }
    }
}

fn build_roundtrip(specs: &[MessageSpec]) -> TokenStream {
    let arms: Vec<TokenStream> = table_specs(specs)
        .map(|s| {
            let snake_ident = format_ident!("{}", name_conv::module_name(&s.name));
            let type_ident = format_ident!("{}", name_conv::type_name(&s.name));
            let name_lit = Literal::string(&s.name);
            quote! {
                #name_lit => {
                    let mut cur = bytes;
                    let msg = <krabka_protocol::owned::#snake_ident::#type_ident as krabka_protocol::Decode>::decode(&mut cur, version)?;
                    expect_consumed(name, cur)?;
                    encode_with(&msg, version)?
                }
            }
        })
        .collect();
    dispatch(
        &arms,
        6,
        "roundtrip",
        (
            &quote!(version: i16, bytes: &[u8]),
            &quote!(version, bytes),
            &quote!(Vec<u8>),
        ),
        &quote! {
            #[doc = " Decode `bytes` as message `name` at `version` and encode it again."]
            #[doc = ""]
            #[doc = " # Errors"]
            #[doc = ""]
            #[doc = " Fails when `name` is unknown, the decode or encode fails, or the decode"]
            #[doc = " leaves bytes behind."]
            pub fn roundtrip(name: &str, version: i16, bytes: &[u8]) -> Result<Vec<u8>, TableError>
        },
    )
}

fn build_header_versions(specs: &[MessageSpec]) -> TokenStream {
    let flex_entries = |message_type: MessageType| -> Vec<TokenStream> {
        specs
            .iter()
            .filter(|s| {
                !s.valid_versions.is_empty()
                    && !s.internal
                    && s.message_type == message_type
                    && s.name != "ApiVersionsResponse"
            })
            .map(|s| {
                let fm_lit = Literal::i16_unsuffixed(super::owned::flex_min(s));
                let name_lit = Literal::string(&s.name);
                quote! { (#name_lit, #fm_lit), }
            })
            .collect()
    };
    let req_entries = flex_entries(MessageType::Request);
    let resp_entries = flex_entries(MessageType::Response);

    quote! {
        const REQUEST_FLEX_MIN: &[(&str, i16)] = &[#(#req_entries)*];
        const RESPONSE_FLEX_MIN: &[(&str, i16)] = &[#(#resp_entries)*];

        fn header_flex_min(table: &[(&str, i16)], name: &str) -> Result<i16, TableError> {
            table
                .iter()
                .find_map(|(candidate, minimum)| (*candidate == name).then_some(*minimum))
                .ok_or_else(|| TableError::UnknownMessage(name.to_owned()))
        }

        #[doc = " The request header version that request `name` uses at `version`."]
        #[doc = ""]
        #[doc = " # Errors"]
        #[doc = ""]
        #[doc = " Fails when `name` is not a known request."]
        pub fn request_header_version(name: &str, version: i16) -> Result<i16, TableError> {
            if name == "ControlledShutdownRequest" && version == 0 {
                return Ok(0);
            }
            let minimum = header_flex_min(REQUEST_FLEX_MIN, name)?;
            Ok(if minimum == i16::MIN || version >= minimum { 2 } else { 1 })
        }

        #[doc = " The response header version that response `name` uses at `version`."]
        #[doc = ""]
        #[doc = " # Errors"]
        #[doc = ""]
        #[doc = " Fails when `name` is not a known response."]
        pub fn response_header_version(name: &str, version: i16) -> Result<i16, TableError> {
            if name == "ApiVersionsResponse" {
                return Ok(0);
            }
            let minimum = header_flex_min(RESPONSE_FLEX_MIN, name)?;
            Ok(i16::from(minimum != i16::MIN && version >= minimum))
        }
    }
}

fn build_strip_frame_header() -> TokenStream {
    quote! {
        #[doc = " Decode and discard the request/response header from a full frame body,"]
        #[doc = " returning the remaining message bytes."]
        #[doc = ""]
        #[doc = " # Errors"]
        #[doc = ""]
        #[doc = " Fails when the frame header is malformed or `name` is unknown."]
        pub fn strip_frame_header(
            name: &str,
            version: i16,
            is_request: bool,
            frame: &[u8],
        ) -> Result<Vec<u8>, TableError> {
            let mut cur = frame;
            if is_request {
                let hv = request_header_version(name, version)?;
                <krabka_protocol::owned::request_header::RequestHeader as krabka_protocol::Decode>::decode(&mut cur, hv)?;
            } else {
                let hv = response_header_version(name, version)?;
                <krabka_protocol::owned::response_header::ResponseHeader as krabka_protocol::Decode>::decode(&mut cur, hv)?;
            }
            Ok(cur.to_vec())
        }
    }
}
